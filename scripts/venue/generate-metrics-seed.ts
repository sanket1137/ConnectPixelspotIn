// Writes migrations/2026_10_venue_metrics_seed.sql: metric definitions (from SEED_METRICS) and the city master
// (STATE_CITIES + every valid state/city pair already used by screens in the LOCAL copy). Re-runnable SQL
// (ON CONFLICT DO NOTHING), so the same file seeds local and production.
//
//   npx tsx scripts/venue/generate-metrics-seed.ts
import fs from "fs";
import path from "path";
import pg from "pg";
import { fileURLToPath } from "url";
import { INDIAN_STATES, STATE_CITIES, normalizeCityName } from "../../shared/constants";
import { seedRegistry } from "../../shared/venueMetrics";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const envLine = fs.readFileSync(path.join(root, ".env.localcopy"), "utf8").split(/\r?\n/).find((l) => l.startsWith("DATABASE_URL="));
const url = envLine?.slice("DATABASE_URL=".length).trim().replace(/^"|"$/g, "") || "";
const host = new URL(url).hostname;
if (host !== "localhost" && host !== "127.0.0.1") {
  console.error(`Refusing: .env.localcopy points at ${host}, not localhost.`);
  process.exit(1);
}

// Same names the data cleanup settled on (scripts/venue/cleanup-values.ts)
const SAME_CITY: Record<string, string> = { Delhi: "New Delhi", Hubli: "Hubballi", Aurangabad: "Chhatrapati Sambhajinagar", Allahabad: "Prayagraj", Gulbarga: "Kalaburagi" };

const q = (v: unknown) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

async function main() {
  const c = new pg.Client({ connectionString: url });
  await c.connect();
  await c.query("set default_transaction_read_only = on");
  const { rows } = await c.query(`select distinct state, city from screens where state is not null and city is not null and trim(city) <> ''`);
  await c.end();

  const states = new Set<string>(INDIAN_STATES);
  const cities = new Map<string, Set<string>>();
  const add = (state: string, city: string) => {
    if (!states.has(state)) return;
    const cleaned = normalizeCityName(city.trim().replace(/\s+/g, " "));
    const name = SAME_CITY[cleaned] ?? cleaned;
    if (!name || /^delhi\s*-/i.test(name)) return; // "Delhi - South" etc. are areas, not cities
    if (!cities.has(state)) cities.set(state, new Set());
    cities.get(state)!.add(name);
  };
  for (const [state, list] of Object.entries(STATE_CITIES)) list.forEach((city) => add(state, city));
  for (const r of rows) add(r.state, r.city);

  const L: string[] = [];
  L.push("-- Generated by scripts/venue/generate-metrics-seed.ts — do not edit by hand. Re-runnable.");
  L.push("-- Seeds venue_metric_definitions (starting metric list, per day) and city_master. Run after 2026_10_venue_metrics.up.sql.");
  L.push("", "BEGIN;", "");
  L.push("INSERT INTO venue_metric_definitions (venue_type, key, label, input_kind, unit, help, options, min_value, max_value, required, show_on_card, role, sort_order, active) VALUES");
  const defRows: string[] = [];
  for (const [type, defs] of Object.entries(seedRegistry())) {
    for (const d of defs) {
      defRows.push(
        `  (${q(type)}, ${q(d.key)}, ${q(d.label)}, ${q(d.kind)}, ${q(d.unit)}, ${q(d.help)}, ${q(JSON.stringify(d.options ?? []))}::jsonb, ${d.min ?? "NULL"}, ${d.max ?? "NULL"}, ${!!d.required}, ${!!d.showOnCard}, ${q(d.role)}, ${d.sortOrder}, true)`
      );
    }
  }
  L.push(defRows.join(",\n"));
  L.push("ON CONFLICT (venue_type, key) DO NOTHING;", "");

  L.push("INSERT INTO city_master (state, city) VALUES");
  const cityRows: string[] = [];
  for (const state of Array.from(cities.keys()).sort()) {
    for (const city of Array.from(cities.get(state)!).sort()) cityRows.push(`  (${q(state)}, ${q(city)})`);
  }
  L.push(cityRows.join(",\n"));
  L.push("ON CONFLICT (state, city) DO NOTHING;", "", "COMMIT;", "");

  const out = path.join(root, "migrations", "2026_10_venue_metrics_seed.sql");
  fs.writeFileSync(out, L.join("\n"));
  console.log(`Definitions: ${defRows.length} · cities: ${cityRows.length} in ${cities.size} states → ${path.relative(root, out)}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
